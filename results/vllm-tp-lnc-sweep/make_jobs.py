#!/usr/bin/env python3
"""Generate the Muse-Glimmer-30B vLLM latency sweep: TP x LNC on the RCT ladder.

Each job is muse-glimmer-30b-vllm-job.yaml with: its own claim template, TP_DEGREE and
NEURON_LOGICAL_NC_CONFIG (must match the template), the node cache for weights and NEFFs, and the
multimodal client (text, image + cases, video, hybrid) run twice: warm-up, then measured.

Usage: python3 make_jobs.py jobs   (from results/vllm-tp-lnc-sweep)
"""
import os
import re
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'muse-glimmer-30b-vllm-job.yaml')
# (tp, lnc, template): smallest rung of the ladder with enough logical cores
MATRIX = [(2, 2, 's-lnc2'), (4, 2, 's-lnc2'), (8, 2, 'm-lnc2'), (16, 2, 'l-lnc2'),
          (2, 1, 's-lnc1'), (4, 1, 's-lnc1'), (8, 1, 's-lnc1'), (16, 1, 'm-lnc1')]

src = open(SRC).read()
assert src.count('m-lnc2') >= 3


def job(tp, lnc, rct):
    name = 'muse-bench-tp%d-lnc%d' % (tp, lnc)
    y = src
    y = re.sub(r'(?m)^(  name: )muse-glimmer-30b-vllm$', r'\g<1>' + name, y, count=1)
    y = y.replace('app: muse-glimmer-30b-vllm\n', 'app: %s\n        bench: muse-tp-lnc\n' % name)
    y = y.replace('name: m-lnc2', 'name: neurons').replace('resourceClaimTemplateName: m-lnc2',
                                                             'resourceClaimTemplateName: %s' % rct)
    # weights, NEFFs and NKI kernels on the node cache (as the deploy): no 60GB download / recompile per job
    old = '              export HF_HOME=/tmp/hf_cache; mkdir -p "$HF_HOME"\n'
    assert y.count(old) == 1
    y = y.replace(old, '              export HF_HOME=/node-cache/hf_cache VLLM_CACHE_ROOT=/node-cache/vllm_cache '
                       'NKI_COMPILE_CACHE_URL=/node-cache/nki_cache\n'
                       '              mkdir -p "$HF_HOME" "$VLLM_CACHE_ROOT" "$NKI_COMPILE_CACHE_URL"\n')
    # client twice: warm-up, then the measured run between markers
    m = re.search(r'(?m)^              python3 vllm_plugin/tests/serve_mm_client\.py .*\n.*\|\| echo "CLIENT FAILED"\n', y)
    assert m, 'client line not found'
    client = m.group(0).replace(' || echo "CLIENT FAILED"', '')
    y = y[:m.start()] + (
        '              echo "════════ WARM-UP CLIENT RUN ════════"\n' + client.rstrip('\n') + ' > /tmp/client_warm.txt 2>&1 || true\n'
        '              echo "════════ BENCH RESULT TP=%d LNC=%d RCT=%s ════════"\n' % (tp, lnc, rct) +
        client.rstrip('\n') + ' || echo "CLIENT FAILED"\n'
        '              echo "════════ END BENCH RESULT ════════"\n') + y[m.end():]
    # env: TP and LNC (LNC must equal the claim template's logicalNeuronCore)
    y = re.sub(r'(- name: TP_DEGREE\n\s+value: )"2"', r'\g<1>"%d"' % tp, y)
    anchor = '            - name: PYTHONUNBUFFERED\n'
    assert y.count(anchor) == 1
    y = y.replace(anchor, '            - name: NEURON_LOGICAL_NC_CONFIG\n              value: "%d"\n' % lnc + anchor)
    # node cache volume + mount
    y = y.replace('          volumeMounts:\n', '          volumeMounts:\n            - name: node-cache\n'
                                                '              mountPath: /node-cache\n', 1)
    y = y.replace('      volumes:\n', '      volumes:\n        - name: node-cache\n          hostPath:\n'
                                     '            path: /opt/muse-glimmer-30b\n            type: DirectoryOrCreate\n', 1)
    hdr = '# Muse latency sweep (generated by make_muse_bench_jobs.py): TP=%d, LNC=%d, %s\n' % (tp, lnc, rct)
    return name, hdr + y


out = sys.argv[1]
os.makedirs(out, exist_ok=True)
for tp, lnc, rct in MATRIX:
    name, y = job(tp, lnc, rct)
    open(os.path.join(out, name + '.yaml'), 'w').write(y)
    print(name, rct)
